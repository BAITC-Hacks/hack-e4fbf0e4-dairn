export type TranslationKey = keyof typeof kazakh;
export type Locale = 'ru' | 'kk';
export type Translate = (
  key: TranslationKey,
  values?: Record<string, string | number>,
) => string;

function translator(locale: Locale): Translate {
  return (key, values) => {
    const text = locale === 'kk' ? kazakh[key] : key;
    return text.replace(/\{(\w+)\}/g, (match, name: string) =>
      String(values?.[name] ?? match),
    );
  };
}
export const translators = { ru: translator('ru'), kk: translator('kk') };
export function isTranslationKey(value: string): value is TranslationKey {
  return Object.hasOwn(kazakh, value);
}
